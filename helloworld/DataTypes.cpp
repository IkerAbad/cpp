#include <iostream>
using namespace std;

int main()
{
    // Type of Numbers
    // int (whole numbers)
    20;
    500;
    -100;
    0;
    // float (7 place precision)
    1.5f;
    9.99f;
    3.14f;
    // double (14 place precision)
    1.5;
    9.99;
    3.14;


    // logical values (boolean) - bool
    true;
    false;

    // character - char (character enclosed in single quotes)
    'a';
    'B';
    '$';
    '5';

    int age = 23;
    cout << age << endl;

}